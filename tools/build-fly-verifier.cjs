function extract(name){
 const re=new RegExp('  function '+name+'\\([^\\n]*?\\)\\s*\\{'),m=re.exec(src);if(!m)throw Error('Missing '+name);
 let i=m.index+m[0].length,depth=1,quote='',comment='';
 for(;i<src.length;i++){
  const c=src[i],next=src[i+1];
  if(comment==='line'){if(c==='\n')comment='';continue;}
  if(comment==='block'){if(c==='*'&&next==='/'){comment='';i++;}continue;}
  if(quote){if(c==='\\'){i++;continue;}if(c===quote)quote='';continue;}
  if(c==='/'&&next==='/'){comment='line';i++;continue;}if(c==='/'&&next==='*'){comment='block';i++;continue;}
  if(c==='"'||c==="'"||c==='`'){quote=c;continue;}
  if(c==='{')depth++;if(c==='}'&&!--depth)return src.slice(m.index,i+1).trim();
 }
 throw Error('Unclosed '+name);
}
